// { text, isUser } for a GE Number, or null for -1 (unreadable).
function formatKarmaGe(ge) {
  if (ge == null || ge < 0) return null;
  if (ge < KARMA_PRESET_GE_COUNT) return { text: `${ge} ${KARMA_PRESET_GE_NAMES[ge]}`, isUser: false };
  const slot = ge - KARMA_PRESET_GE_COUNT;
  if (slot < KARMA_USER_GE_BANK_SIZE) {
    return { text: `User GE U-A ${String(slot).padStart(3, "0")}`, isUser: true };
  }
  return { text: `User GE ${ge}`, isUser: true };
}

// Tooltip for a User GE reference.
const KARMA_USER_GE_TITLE =
  "A User GE: it comes from a .KGE file loaded on the Kronos (the factory PRELOAD.KGE is one), " +
  "not from this PCG -- the KARMA part only sounds right where the same KGE is loaded.";

// A <span> showing one GE reference (empty for -1); a User GE gets the
// is-user look and KARMA_USER_GE_TITLE as its tooltip.
function karmaGeSpan(ge) {
  const span = document.createElement("span");
  const f = formatKarmaGe(ge);
  span.className = "karma-ge" + (f && f.isUser ? " is-user" : "");
  span.textContent = f ? f.text : "";
  if (f && f.isUser) span.title = KARMA_USER_GE_TITLE;
  return span;
}
