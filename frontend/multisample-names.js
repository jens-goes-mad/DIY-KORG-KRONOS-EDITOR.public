// "ROM" / "EXs<n>" for a zone with a legacy bank number (0 ROM, 1 Sampling
// RAM, 2 = EXs1 ...).
function legacyMultisampleBankName(legacyBank) {
  if (legacyBank === 0) return "ROM";
  if (legacyBank === 1) return "Sampling RAM";
  return `EXs${legacyBank - 1}`;
}

