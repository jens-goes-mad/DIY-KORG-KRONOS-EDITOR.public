function stereoMultisampleNames(bank) {
  if (!stereoMultisampleCache[bank]) {
    const list = KORG_MULTISAMPLE_NAMES[bank] || [];
    const pairs = [];
    for (let i = 0; i + 1 < list.length; i++) {
      const l = list[i].match(/^(.*?)\s*-L$/), r = list[i + 1].match(/^(.*?)\s*-R$/);
      if (l && r && l[1] === r[1]) pairs.push(l[1]);
    }
    stereoMultisampleCache[bank] = pairs;
  }
  return stereoMultisampleCache[bank];
}

// { text, title } for one played zone from getProgramUsage()'s "samples".
// How a ROM/EXs zone's MS Number counts (format doc §5.8, checked
// 2026-11-15 against Korg's factory Programs): mono -> the library's full
// list; stereo -> its stereo pairs only (all 270 stereo references in
// K1/PRELOAD.PCG land on fitting names, e.g. "Eleanor Rigby Strings" ->
// ROM stereo 10 "Strings Ensemble 1"). A user bank's stereo reference uses
// the -L number instead (§5.8), but has no name here anyway.
function formatPlayedMultisample(z) {
  const number = String(z.msNumber).padStart(3, "0");
  const stereo = z.stereo ? " (stereo)" : "";
  if (z.kind === "rom" || z.kind === "exs" || z.kind === "oldRam") {
    const bank = legacyMultisampleBankName(z.legacyBank);
    const list = z.stereo ? stereoMultisampleNames(bank) : KORG_MULTISAMPLE_NAMES[bank];
    const name = list && list[z.msNumber] ? list[z.msNumber] : "";
    const title = z.kind === "oldRam" ? "Sampling-mode RAM -- the name is in the instrument's sample memory, not in this file" : "";
    return { text: `${bank} ${number}${name ? " " + name : ""}${stereo}`, title };
  }
  if (z.kind === "user") {
    const bankId = sampleBankId(z.uuid);
    return {
      text: `User bank ${bankId} ${number}${stereo}`,
      title: `Multisample ${z.msNumber} of the user sample bank ${bankId}. Its name is in that bank's .KSC file.`,
      status: sampleBankStatus(bankId),
    };
  }
  return { text: `Invalid bank ${number}`, title: z.uuid };
}

// A user sample bank's ID as its .KSC writes it (`#uuid:...`): a zone that
// plays a stereo multisample stores the ID with byte 15 bit 0 set (format
// doc §5.8 -- `...ff37` for the KSC's `...ff36`), so that bit is cleared here.
function sampleBankId(uuid) {
  const last = parseInt(uuid.slice(-2), 16);
  return uuid.slice(0, -2) + (last & 0xfe).toString(16).padStart(2, "0");
}

// "attached" when a .KSC with this bank ID is attached to the dataset,
// otherwise "unreferenced". The editor doesn't load or attach KSC files yet
// (STATE.md's KSC plan), so every user bank is "unreferenced" for now.
function sampleBankStatus(bankId) {
  return "unreferenced";
}

